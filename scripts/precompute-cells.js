// Runs the browser solver in Node and writes src/lab/precomputed.ts: the default result per target (shown before
// or instead of a live run) and a pool of vetted seeds, so every live run starts from a different random design.
// Usage: node scripts/precompute-cells.js
const { execFileSync } = require("child_process");
const fs = require("fs");
const os = require("os");
const path = require("path");

const root = path.resolve(__dirname, "..");
const out = fs.mkdtempSync(path.join(os.tmpdir(), "cells-"));
execFileSync(process.execPath, [require.resolve("typescript/bin/tsc"), "--outDir", out, "--module", "commonjs",
  "--target", "es2019", "--skipLibCheck", path.join(root, "src/lab/unitcell.ts")], { stdio: "inherit" });
const { createRun, OBJECTIVES } = require(path.join(out, "unitcell.js"));

const N = 32;
const q = (a) => Buffer.from(Uint8Array.from(a, (v) => Math.round(Math.min(1, Math.max(0, v)) * 255))).toString("base64");
const r = (v, d = 4) => Number(v.toFixed(d));

const cells = {};
let initial = "";   // the design the solver evaluates first (same for every target)
for (const obj of OBJECTIVES) {
  const run = createRun(obj, { n: N });
  const hist = { E1: [], G12: [], nu12: [] };
  let it;
  do {
    it = run.next();
    if (!initial) initial = q(it.phys);
    hist.E1.push(r(it.E1)); hist.G12.push(r(it.C[8])); hist.nu12.push(r(it.nu12));
  } while (!it.done);
  cells[obj] = { rho: q(it.phys), iter: it.iter, vol: r(it.vol), E1: r(it.E1), G12: r(it.C[8]), nu12: r(it.nu12), C: Array.from(it.C, (v) => r(v)), hist };
  console.log(obj, "iter", it.iter, "vol", r(it.vol), "E1", r(it.E1), "G12", r(it.C[8]), "nu12", r(it.nu12));
}

// Solid phase (density > 0.5) as one connected piece on the periodic cell: no floating islands.
function connected(phys) {
  const seen = new Uint8Array(N * N), solid = (e) => phys[e] > 0.5;
  const start = phys.findIndex((v) => v > 0.5);
  if (start < 0) return false;
  const stack = [start]; seen[start] = 1; let count = 1;
  while (stack.length) {
    const e = stack.pop(), x = e % N, y = (e / N) | 0;
    for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
      const f = ((y + dy + N) % N) * N + ((x + dx + N) % N);
      if (!seen[f] && solid(f)) { seen[f] = 1; count++; stack.push(f); }
    }
  }
  return count === phys.filter((v) => v > 0.5).length;
}

// A seed joins the pool when its run converges to a crisp, connected design that is distinct from the others
// (and, for the auxetic target, clearly negative in Poisson's ratio).
const CANDIDATES = 40, KEEP = 16, seeds = {};
for (const obj of OBJECTIVES) {
  seeds[obj] = [];
  const keys = new Set();
  for (let k = 1; k <= CANDIDATES && seeds[obj].length < KEEP; k++) {
    const seed = k * 7919, run = createRun(obj, { n: N, seed });
    let it;
    do it = run.next(); while (!it.done);
    const grey = it.phys.filter((v) => v > 0.1 && v < 0.9).length / it.phys.length;
    const key = [it.E1, it.C[8], it.nu12].map((v) => v.toFixed(3)).join();
    const ok = it.iter < run.P.o.maxIter && grey < 0.05 && connected(it.phys) && !keys.has(key) && (obj !== "auxetic" || it.nu12 < -0.2);
    if (ok) { keys.add(key); seeds[obj].push(seed); }
    console.log(obj, seed, ok ? "kept" : "skipped", "iter", it.iter, "grey", grey.toFixed(3), "nu12", it.nu12.toFixed(3));
  }
}

const ts = `// Generated by scripts/precompute-cells.js. Do not edit.
export const N = ${N};
export const initial = "${initial}";
export const cells = ${JSON.stringify(cells)} as const;
export const seeds: Record<string, number[]> = ${JSON.stringify(seeds)};
`;
fs.writeFileSync(path.join(root, "src/lab/precomputed.ts"), ts);
fs.rmSync(out, { recursive: true, force: true });
console.log("wrote src/lab/precomputed.ts", ts.length, "bytes");
