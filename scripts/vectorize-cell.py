"""Vectorize the auxetic unit cell from the MSc thesis into periodic SVG cut paths.

Source: public/GUVEN_THESIS.pdf, Fig. 8.1(b), the AutoCAD idealization of the
nonlinear negative-Poisson's-ratio topology. Output: src/content/auxeticCell.ts,
the void outlines of one cell in a 0..100 box (each void listed once per period).

Run: python scripts/vectorize-cell.py   (needs PyMuPDF, scikit-image, Pillow)
"""
import io
import fitz
import numpy as np
from PIL import Image
from skimage import filters, measure

doc = fitz.open("public/GUVEN_THESIS.pdf")
page = doc[78]  # thesis p. 65, Fig. 8.1
# the four panels are square; (b) is the second from the left (skips the page watermark)
panels = [im for im in page.get_images(full=True) if abs(page.get_image_bbox(im).width - page.get_image_bbox(im).height) < 2]
img = sorted(panels, key=lambda im: page.get_image_bbox(im).x0)[1]
png = fitz.Pixmap(doc, img[0]).tobytes("png")
g = np.asarray(Image.open(io.BytesIO(png)).convert("L")) / 255

line = g > 0.45                                   # white CAD outline on dark background
ys, xs = np.nonzero(line)
x0, y0 = xs.min(), ys.min()
n = min(xs.max() - x0, ys.max() - y0)             # square cell frame
lab = measure.label(~line, connectivity=1)
regions = measure.regionprops(lab)
inner = [r for r in regions if r.bbox[0] > 0 and r.bbox[1] > 0]   # not touching image edge
solid_label = max(inner, key=lambda r: r.bbox[2] - r.bbox[0]).label  # spans the whole cell
m = ((lab == solid_label) | line).astype(float)[y0:y0 + n, x0:x0 + n]
m = (m + m[:, ::-1] + m[::-1, :] + m[::-1, ::-1]) / 4                 # exact mirror symmetry

t = filters.gaussian(np.tile(m, (3, 3)), 1.2, mode="wrap")
voids = []
for c in measure.find_contours(t, 0.5):
    if not np.allclose(c[0], c[-1]):
        continue
    cy, cx = c[:, 0].mean(), c[:, 1].mean()
    if not (n <= cx < 2 * n and n <= cy < 2 * n):  # keep each void once per period
        continue
    c = measure.approximate_polygon(c, 0.35)
    pts = [((x - n) / n * 100, (y - n) / n * 100) for y, x in c[:-1]]
    voids.append("M" + "L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + "Z")

assert len(voids) == 4, f"expected 4 voids per cell, got {len(voids)}"
body = ",\n".join(f'  "{v}"' for v in voids)
with open("src/content/auxeticCell.ts", "w") as f:
    f.write(
        "// Generated by scripts/vectorize-cell.py from the MSc thesis, Fig. 8.1(b).\n"
        "// Void outlines (laser cut paths) of one auxetic unit cell in a 0..100 box.\n"
        "// Tile by translating multiples of 100 in x and y.\n"
        f"export const auxeticCellVoids: string[] = [\n{body},\n];\n"
    )
print("wrote src/content/auxeticCell.ts with", len(voids), "voids")
